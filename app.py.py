def create_profile(name, role, university, department, data):
    data = deepcopy(data)
    name = clean_text(name)
    role = clean_text(role)
    university = clean_text(university)
    department = clean_text(department) or "General"

    if not name:
        return data, "⚠️ Please enter your name.", dashboard_stats(data), header_user(data), *show_page(0), *sidebar_visibility(data)
    if role not in ("Senior", "Junior"):
        return data, "⚠️ Please select Senior or Junior.", dashboard_stats(data), header_user(data), *show_page(0), *sidebar_visibility(data)
    if not university:
        return data, "⚠️ Please enter your university.", dashboard_stats(data), header_user(data), *show_page(0), *sidebar_visibility(data)

    existing = data["seniors"] if role == "Senior" else data["juniors"]
    duplicate = any(
        normalize(p["name"]) == normalize(name)
        and normalize(p["university"]) == normalize(university)
        and normalize(p["department"]) == normalize(department)
        for p in existing
    )
    if duplicate:
        return data, "⚠️ This profile already exists.", dashboard_stats(data), header_user(data), *show_page(0), *sidebar_visibility(data)

    person = {"name": name, "university": university, "department": department}
    existing.append(person)

    if normalize(university) not in [normalize(u) for u in data["universities"]]:
        data["universities"].append(university)

    data["current_user"] = name
    data["current_role"] = role
    data["settings"]["name"] = name
    data["settings"]["university"] = university

    next_page = 2 if role == "Senior" else 1
    role_message = "Senior Questions" if role == "Senior" else "Ask a Question"

    message = f"""
### ✅ Registration Successful!

Welcome **{name}** 🎉

👤 **Role:** {role}
🏫 **University:** {university}
📚 **Department:** {department}

Your next menu is now **{role_message}**.
"""

    return data, message, dashboard_stats(data), header_user(data), *show_page(next_page), *sidebar_visibility(data)

