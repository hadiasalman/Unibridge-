def upload_data(files, data):
    data = deepcopy(data)
    if not files:
        return data, "⚠️ Please select at least one file."
    for file in files:
        name = getattr(file, "name", str(file)).replace("\\", "/").split("/")[-1]
        if name not in data["uploaded_files"]:
            data["uploaded_files"].append(name)
    output = "### ✅ Files Added\n\n" + "\n".join(f"📄 **{n}**" for n in data["uploaded_files"])
    return data, output + "\n\n> ℹ️ UniBridge currently stores uploaded filenames."


