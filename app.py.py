def find_senior(university, department, data):
    university, department = clean_text(university), clean_text(department)
    if not data["seniors"]:
        return "## 👨‍🎓 No Senior Found\n\nThere are currently **no seniors registered on UniBridge**."
    su, sd = normalize(university), normalize(department)
    results = [s for s in data["seniors"] if (not su or su in normalize(s["university"])) and (not sd or sd in normalize(s["department"]))]
    if not results:
        return "## 🔍 No Matching Senior\n\nNo senior matches your search."
    return "## 👨‍🎓 Available Seniors\n\n" + "\n---\n".join(
        f"### 👤 {s['name']}\n\n🏫 **University:** {s['university']}  \n📚 **Department:** {s['department']}  \n🟢 **Available for Guidance**"
        for s in results
    )


def find_junior(university, department, data):
    university, department = clean_text(university), clean_text(department)
    if not data["juniors"]:
        return "## 🎓 No Junior Found\n\nThere are currently **no juniors registered on UniBridge**."
    su, sd = normalize(university), normalize(department)
    results = [j for j in data["juniors"] if (not su or su in normalize(j["university"])) and (not sd or sd in normalize(j["department"]))]
    if not results:
        return "## 🔍 No Matching Junior\n\nNo junior matches your search."
    return "## 🎓 Available Juniors\n\n" + "\n---\n".join(
        f"### 👤 {j['name']}\n\n🏫 **University:** {j['university']}  \n📚 **Department:** {j['department']}"
        for j in results
    )

