def header_user(data):
    if data.get("current_user"):
        role = data.get("current_role", "")
        suffix = f" ({role})" if role else ""
        return f"👤 <b>{data['current_user']}{suffix}</b>"
    return "👤 <b>Guest User</b>"


def show_page(number):
    return [gr.update(visible=(i == number)) for i in range(10)]


def get_unanswered_question_choices(data):
    choices = []
    for q in data.get("questions", []):
        if not clean_text(q.get("answer", "")):
            qid = int(q["id"])
            text = clean_text(q.get("question", "")).replace("\n", " ")
            if len(text) > 90:
                text = text[:87] + "..."
            choices.append((f"Q{qid:03d} — {text}", qid))
    return choices


def refresh_question_dropdown(data):
    return gr.update(choices=get_unanswered_question_choices(data), value=None)


def unanswered_questions_markdown(data):
    questions = [q for q in data.get("questions", []) if not clean_text(q.get("answer", ""))]
    if not questions:
        return "## 💬 Questions\n\nThere are currently **no unanswered questions**."

    output = "## 💬 Questions Waiting for Senior Answers\n\n"
    for q in questions:
        output += f"""
<div class="question-card">
<div class="question-id">Q{int(q['id']):03d}</div>

### {q['question']}

📚 **Department:** {q.get('department', 'General')}
👤 **Asked by:** {q.get('asked_by', 'Guest')}
</div>
"""
    return output


def build_history(data):
    if not data.get("questions"):
        return "## 📜 History\n\nNo questions have been answered yet."

    answered = [q for q in data["questions"] if clean_text(q.get("answer", ""))]
