def add_question(question, department, data):
    data = deepcopy(data)
    question = clean_text(question)
    department = clean_text(department) or "General"

    if not data.get("current_user") or data.get("current_role") != "Junior":
        return data, "⚠️ Only a registered Junior can ask a community question.", dashboard_stats(data), unanswered_questions_markdown(data), refresh_question_dropdown(data), build_history(data)

    if not question:
        return data, "⚠️ Please enter your question.", dashboard_stats(data), unanswered_questions_markdown(data), refresh_question_dropdown(data), build_history(data)

    # Always calculate the next unused ID, even if questions were deleted later.
    used_ids = [int(q.get("id", 0)) for q in data.get("questions", [])]
    question_id = max(used_ids, default=0) + 1

    data["questions"].append({
        "id": question_id,
        "question": question,
        "department": department,
        "asked_by": data["current_user"],
        "answer": "",
        "answered_by": ""
    })

    return (
        data,
        f"✅ Your question has been posted with **Question ID Q{question_id:03d}**. Seniors can now answer it.",
        dashboard_stats(data),
        unanswered_questions_markdown(data),
        refresh_question_dropdown(data),
        build_history(data)
    )


def answer_question(question_id, answer, data):
    data = deepcopy(data)
    answer = clean_text(answer)

    if data.get("current_role") != "Senior":
        return data, "⚠️ Only a registered Senior can answer questions.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    if question_id in (None, ""):
        return data, "⚠️ Please select a question from the dropdown.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    if not answer:
        return data, "⚠️ Please write an answer.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    try:
        question_id = int(question_id)
    except (TypeError, ValueError):
        return data, "⚠️ Invalid question selection.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    target = next((q for q in data["questions"] if int(q.get("id", -1)) == question_id), None)
    if target is None:
        return data, "⚠️ The selected question was not found.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    if clean_text(target.get("answer", "")):
        return data, f"⚠️ Q{question_id:03d} has already been answered.", unanswered_questions_markdown(data), build_history(data), refresh_question_dropdown(data), dashboard_stats(data)

    target["answer"] = answer
    target["answered_by"] = data["current_user"]
    data["answers"].append({
        "question_id": question_id,
        "answer": answer,
        "answered_by": data["current_user"]
    })

    return (
        data,
        f"✅ Answer to **Q{question_id:03d}** has been posted and moved to History.",
        unanswered_questions_markdown(data),
        build_history(data),
        refresh_question_dropdown(data),
        dashboard_stats(data)
    )

